export function getLanguage() {
  if (typeof localStorage !== "undefined") {
    const saved = localStorage.getItem("fintrack_settings");
    if (saved) {
      try {
        const parsed = JSON.parse(saved);
        if (parsed.language) return parsed.language;
      } catch (e) {
        console.error("Error reading language from settings:", e);
      }
    }
  }
  return "th";
}

export function t(key, params = {}) {
  const lang = getLanguage();
  const dict = dictionary[lang] || dictionary.th;
  let text = dict[key] || dictionary.th[key] || key;

  if (typeof text !== "string") return text;

  Object.keys(params).forEach(paramKey => {
    text = text.replaceAll(`{${paramKey}}`, String(params[paramKey]));
  });

  return text;
}

export function locale() {
  return getLanguage() === "en" ? "en-US" : "th-TH";
}
